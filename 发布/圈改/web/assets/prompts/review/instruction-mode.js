export function exportDeliveryInstruction(mode, original) {
  const size = original
    ? `（${original.width} × ${original.height} 像素）`
    : "";
  if (mode === "image")
    return `交付完整成品 PNG，默认保持原图尺寸${size}；“区域变宽/变窄”默认指圈选对象，不等于缩放整张画布。用户明确要求改变画布尺寸时按原文执行并说明。`;
  return `交付实际修改的项目文件及验证结果；核对 PNG 必须来自真实修改后的页面或幻灯片，尽量采用与原图${size}相同的视角、缩放或渲染尺寸，不拉伸、不裁掉内容来凑尺寸。`;
}
